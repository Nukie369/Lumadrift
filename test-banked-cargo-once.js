'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('game.js','utf8');
const match = source.match(/  function finish\(success,crashed\)\{[\s\S]*?\}\n  function claimDaily\(/);
assert.ok(match,'finish implementation exists');
const finishSource=match[0].slice(0,-'\n  function claimDaily('.length);
const state={energy:0,credits:200,total:500,best:250,xp:40,wins:2,dailyProgress:{banked:500}};
let saves=0, finished=0;
const context={state,nf:new Intl.NumberFormat('en-US'),beep(){},revealRelic(){throw Error('No relic on depth-one flight');},addMissionStat(key,amount){state.dailyProgress[key]=(state.dailyProgress[key]||0)+amount;},track(type){if(type==='finish')finished++;},sceneMessage(){},updateScene(){},renderHeader(){},renderAtlas(){},save(){saves++;},markFlight(){}};
vm.createContext(context);
vm.runInContext('let run=null;'+finishSource+';globalThis.finishOnce=(flight)=>{run=flight;finish(false,false)};globalThis.finishAgain=()=>finish(false,false)',context);
context.finishOnce({practice:false,cargo:75,depth:1,hull:2});
assert.equal(state.credits,275,'banked cargo credited');
assert.equal(state.total,575,'lifetime total updated');
assert.equal(state.dailyProgress.banked,575,'mission progress updated');
assert.equal(state.wins,3);
const snapshot=JSON.stringify(state);
context.finishAgain();
assert.equal(JSON.stringify(state),snapshot,'repeated finish cannot credit again');
assert.equal(finished,1,'only one finish event');
assert.equal(saves,1,'only one save');
console.log('Banked cargo is credited once even if finish is invoked twice');
