'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const source=fs.readFileSync('game.js','utf8');
const handlerMatch=source.match(/\$\('again-btn'\)\.addEventListener\('click',(\(\)=>\{[^\n]*?\})\);/);
assert.ok(handlerMatch,'results replay click handler exists');
const state={energy:0,credits:320,end:{earned:55},dailyProgress:{launches:2}};
const calls=[];let listener;let rechargeOnNextClick=false;let notice='';
const button={dataset:{replayMode:'practice'},addEventListener:(name,fn)=>{assert.equal(name,'click');listener=fn;}};
const context={state,$:id=>button,regen:()=>{if(rechargeOnNextClick){state.energy=1;rechargeOnNextClick=false;}},launch:practice=>calls.push(practice),renderReplayChoice:()=>{button.dataset.replayMode=state.energy>0?'standard':'practice';},notify:msg=>{notice=msg;}};
vm.runInNewContext(`$('again-btn').addEventListener('click',${handlerMatch[1]});`,context);
listener();listener();
assert.deepEqual(calls,[true,true],'two consecutive zero-fuel replays select practice');
assert.equal(state.credits,320,'replay selection does not change wallet');
assert.equal(state.energy,0,'replay selection does not consume fuel');
assert.equal(state.dailyProgress.launches,2,'replay selection does not advance missions');
assert.equal(state.end.earned,55,'replay selection does not discard banked result');
rechargeOnNextClick=true;listener();
assert.deepEqual(calls,[true,true,true],'displayed Practice remains free when fuel recharges on click');
button.dataset.replayMode='standard';listener();
assert.deepEqual(calls,[true,true,true,false],'standard replay works with available fuel');
state.energy=0;listener();
assert.deepEqual(calls,[true,true,true,false],'stale standard choice does not silently launch Practice');
assert.equal(button.dataset.replayMode,'practice');
assert.match(notice,/Free Practice/);
listener();
assert.deepEqual(calls,[true,true,true,false,true],'explicit Practice selection launches at zero fuel');
console.log('Replay handler: two practice selections, recharge, and stale standard choice pass');
