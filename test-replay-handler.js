'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const source=fs.readFileSync('game.js','utf8');
const handlerMatch=source.match(/\$\('again-btn'\)\.addEventListener\('click',(\(\)=>\{[^\n]*?\})\);/);
assert.ok(handlerMatch,'results replay click handler exists');
const state={energy:0,credits:320,end:{earned:55},dailyProgress:{launches:2}};
const calls=[];let listener;
const context={state,$:id=>({addEventListener:(name,fn)=>{assert.equal(name,'click');listener=fn;}}),regen:()=>{},launch:practice=>calls.push(practice)};
vm.runInNewContext(`$('again-btn').addEventListener('click',${handlerMatch[1]});`,context);
listener();listener();
assert.deepEqual(calls,[true,true],'two consecutive zero-fuel replays select practice');
assert.equal(state.credits,320,'replay selection does not change wallet');
assert.equal(state.energy,0,'replay selection does not consume fuel');
assert.equal(state.dailyProgress.launches,2,'replay selection does not advance missions');
assert.equal(state.end.earned,55,'replay selection does not discard banked result');
state.energy=1;listener();assert.deepEqual(calls,[true,true,false],'recharged fuel selects standard flight at click time');
console.log('Replay handler: consecutive practice and recharge selection pass');
