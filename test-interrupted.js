const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync(__dirname+'/game.js','utf8');
const start=src.indexOf('  const FLIGHT_STORAGE=');
const end=src.indexOf('  let run=null',start);
assert(start>0&&end>start);
const store=new Map();let now=Date.now();
const localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const ctx={localStorage,Date:{now:()=>now},STORAGE:'test_save'};
vm.createContext(ctx);vm.runInContext(src.slice(start,end)+';this.markFlight=markFlight;this.interruptedFlight=interruptedFlight;',ctx);
assert.strictEqual(ctx.interruptedFlight(),null);
ctx.markFlight({practice:false,depth:2});
assert.match(ctx.interruptedFlight(),/Unbanked virtual cargo/);
assert.strictEqual(ctx.interruptedFlight(),null,'recovery notice should appear once');
ctx.markFlight({practice:true,depth:1});
assert.match(ctx.interruptedFlight(),/practice flight/);
ctx.markFlight({practice:false,depth:0});ctx.markFlight(null);
assert.strictEqual(ctx.interruptedFlight(),null,'completed flight must not show interruption');
store.set('test_save_active_flight','{corrupt');assert.strictEqual(ctx.interruptedFlight(),null);
store.set('test_save_active_flight',JSON.stringify({started:now-8*86400000,practice:false}));assert.strictEqual(ctx.interruptedFlight(),null);
console.log('PASS: normal, interrupted, practice, completed, corrupt, expired flight markers');
